  public static UiCopy For(string? language) =>
    UiLanguage.Normalize(language) == UiLanguage.It ? Italian() : English();

  public string Items(int total) =>
    total == 1 ? ItemOne : string.Format(ItemsMany, total);

  public string StatsLine(string folder, int total, int unread, int shown) {
    var items = Items(Math.Max(0, total));
    var counts = shown > 0 && shown < total
      ? string.Format(ShownOf, shown, items)
      : items;
    if (unread > 0)
      counts += string.Format(UnreadSuffix, unread);
    return folder + "  ·  " + counts;
  }

  public string IndexLine(int done, int total) =>
    total <= 0 ? "" : string.Format(Indexing, Math.Clamp(done, 0, total), total);

  public string IndexLine(int done, int total, string folder) =>
    total <= 0
      ? IndexScan(folder)
      : string.Format(IndexingWithFolder, folder, Math.Clamp(done, 0, total), total);

  public string IndexScan(string folder) =>
    string.Format(IndexingScan, folder);

  public string ArchivePathHint(string path) =>
    string.Format(ArchiveHint, path);

